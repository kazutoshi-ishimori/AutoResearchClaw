"""Render the paper's Figure 2 (coverage grid) and Table 1 (evidence) as LaTeX.

These are **pure functions of ``run_suite`` output**. Generating the figure and
table mechanically — rather than hand-transcribing check-marks and numbers — is
the paper's own thesis applied to its own artifacts: every cell traces to an
``AttackOutcome`` a verification layer actually produced, and a future
regression (a defense that stops catching its attack) renders as ``\\miss``
instead of being silently copied away.

Symbols are emitted as semantic macros so the paper's preamble owns their look
(and so the fragments compile under any engine). Define, e.g.::

    \\newcommand{\\caught}{$\\checkmark$}    % true positive, honest-clean
    \\newcommand{\\gap}{$\\triangle$}         % uncaught by design (T3′)
    \\newcommand{\\miss}{$\\times$}           % missed attack — a regression
    \\newcommand{\\falsepos}{$\\otimes$}      % fired on the honest control — a regression

Both renderers accept the same ``columns`` (one per dataset, e.g. IPF + COVID)
and a ``harness_commit`` string; each emits a provenance header binding every
column's ledger path + sha256 and the harness commit that produced the numbers.
"""

from __future__ import annotations

from dataclasses import dataclass

from researchclaw.experiment.verify.fabrication_attacks import AttackOutcome


@dataclass(frozen=True)
class Column:
    """One dataset column of the coverage matrix.

    ``outcomes`` is exactly a ``run_suite(scenario)`` result (or a hand-built
    list, for tests); ``ledger_path``/``ledger_sha256`` bind the column to the
    provenance ledger the numbers were recomputed from.
    """

    label: str
    ledger_path: str
    ledger_sha256: str
    outcomes: tuple[AttackOutcome, ...]


def _symbol(o: AttackOutcome) -> str:
    """The grid cell for one outcome — faithful to *both* dimensions the harness
    reports: it caught the attack (true positive) AND it left the honest control
    green (no false positive).

    Precedence puts the honest control first, so a defense that fires on honest
    input can never be masked — not even on a by-design-gap or caught row::

        honest_passes is False → ``\\falsepos``  (fired on the honest control)
        by_design_gap          → ``\\gap``       (uncaught by design)
        detected               → ``\\caught``    (true positive, honest-clean)
        otherwise              → ``\\miss``       (a genuine detection regression)

    This makes regression-visibility symmetric: a missed attack renders
    ``\\miss`` and its dual — a false positive on honest input — renders
    ``\\falsepos``. Neither is ever silently copied away as ``\\caught``.
    """
    if not o.honest_passes:
        return r"\falsepos"
    if o.by_design_gap:
        return r"\gap"
    if o.detected:
        return r"\caught"
    return r"\miss"


def _fmt_num(val: float | None) -> str:
    if val is None:
        return "--"
    if isinstance(val, float) and val.is_integer():
        return str(int(val))
    return f"{val:.6g}"


def _fmt_evidence(evidence: tuple[tuple[str, float, float | None], ...]) -> str:
    """``claimed \\to recomputed`` per metric, ``;``-joined; ``--`` when empty."""
    if not evidence:
        return "--"
    parts = [
        rf"{_fmt_num(claimed)}\,$\to$\,{_fmt_num(recomputed)}"
        for _name, claimed, recomputed in evidence
    ]
    return "; ".join(parts)


def _latex_escape(text: str) -> str:
    for a, b in (("\\", r"\textbackslash{}"), ("_", r"\_"), ("&", r"\&"),
                 ("%", r"\%"), ("#", r"\#"), ("$", r"\$")):
        text = text.replace(a, b)
    return text


def _provenance_header(columns: list[Column], harness_commit: str) -> list[str]:
    lines = [
        "% GENERATED by researchclaw.experiment.verify.coverage_report —"
        " do not edit by hand.",
        "% UTF-8 (layer glyphs ①–⑤, arrows); compile with xelatex/lualatex,"
        " and define \\caught \\gap \\miss \\falsepos in the preamble.",
        f"% harness commit: {harness_commit}",
    ]
    for c in columns:
        lines.append(f"% column {c.label}: {c.ledger_path} @ sha256 {c.ledger_sha256}")
    return lines


def _ordered_attack_ids(columns: list[Column]) -> list[str]:
    """Attack ids in first-column order, unioned with any others (stable)."""
    seen: list[str] = []
    for c in columns:
        for o in c.outcomes:
            if o.attack_id not in seen:
                seen.append(o.attack_id)
    return seen


def _by_id(column: Column) -> dict[str, AttackOutcome]:
    return {o.attack_id: o for o in column.outcomes}


def render_figure2(columns: list[Column], *, harness_commit: str) -> str:
    """The compact attack × dataset grid (Figure 2)."""
    maps = [_by_id(c) for c in columns]
    attack_ids = _ordered_attack_ids(columns)
    col_spec = "l" + "c" * len(columns)

    out = _provenance_header(columns, harness_commit)
    out.append(r"\begin{tabular}{" + col_spec + "}")
    out.append(r"\toprule")
    header = "Attack & " + " & ".join(_latex_escape(c.label) for c in columns) + r" \\"
    out.append(header)
    out.append(r"\midrule")
    for aid in attack_ids:
        cells = [_latex_escape(aid)]
        for m in maps:
            o = m.get(aid)
            cells.append(_symbol(o) if o is not None else "--")
        out.append(" & ".join(cells) + r" \\")
    out.append(r"\bottomrule")
    out.append(r"\end{tabular}")
    return "\n".join(out) + "\n"


def _representative(maps: list[dict[str, AttackOutcome]], aid: str) -> AttackOutcome | None:
    """The first column's outcome for an attack — supplies the layer/note text,
    which is dataset-independent."""
    for m in maps:
        if aid in m:
            return m[aid]
    return None


def _note_bits(rep: AttackOutcome | None) -> list[str]:
    """The dataset-independent note pieces for one attack: by-design gap,
    conditional guard, and free-form detail (LaTeX-escaped)."""
    bits: list[str] = []
    if rep is not None:
        if rep.by_design_gap:
            bits.append("by-design gap")
        if rep.conditional_on:
            bits.append(f"cond.\\ {_latex_escape(rep.conditional_on)}")
        if rep.detail:
            bits.append(_latex_escape(rep.detail))
    return bits


def render_table1(columns: list[Column], *, harness_commit: str) -> str:
    """The detailed per-row evidence table (Table 1).

    Columns: attack id, layer, then ``caught`` + ``claimed → recomputed`` for
    each dataset. The per-attack notes (by-design / conditional / detail) are
    emitted separately by :func:`render_evidence_notes` for the caption, so the
    body stays legible at a fixed font size without a ``\\resizebox``.
    """
    maps = [_by_id(c) for c in columns]
    attack_ids = _ordered_attack_ids(columns)
    # id | layer | (caught, evidence) per dataset
    col_spec = "ll" + "cl" * len(columns)

    out = _provenance_header(columns, harness_commit)
    out.append(r"\begin{tabular}{" + col_spec + "}")
    out.append(r"\toprule")
    head = ["Attack", "Layer"]
    for c in columns:
        head.append(_latex_escape(c.label))
        head.append(rf"{_latex_escape(c.label)}: claimed\,$\to$\,recomp.")
    out.append(" & ".join(head) + r" \\")
    out.append(r"\midrule")

    for aid in attack_ids:
        rep = _representative(maps, aid)
        row = [_latex_escape(aid), _latex_escape(rep.layer) if rep else "--"]
        for m in maps:
            o = m.get(aid)
            if o is None:
                row.extend(["--", "--"])
            else:
                row.append(_symbol(o))
                row.append(_fmt_evidence(o.evidence))
        out.append(" & ".join(row) + r" \\")
    out.append(r"\bottomrule")
    out.append(r"\end{tabular}")
    return "\n".join(out) + "\n"


def render_evidence_notes(columns: list[Column], *, harness_commit: str) -> str:
    """The per-attack notes for Table 1's caption — one ``\\textbf{id}~note.``
    clause per attack that carries a note, flowed as a paragraph.

    These are dataset-independent (taken from the first column that has each
    attack), so relocating them from a body column into the caption loses no
    information while letting the body render at a fixed font size. Carries the
    same provenance header as the table it annotates.
    """
    maps = [_by_id(c) for c in columns]
    attack_ids = _ordered_attack_ids(columns)

    out = _provenance_header(columns, harness_commit)
    clauses = []
    for aid in attack_ids:
        bits = _note_bits(_representative(maps, aid))
        if bits:
            clauses.append(rf"\textbf{{{_latex_escape(aid)}}}~{'; '.join(bits)}.")
    out.append(" ".join(clauses))
    return "\n".join(out) + "\n"


__all__ = ["Column", "render_figure2", "render_table1", "render_evidence_notes"]
